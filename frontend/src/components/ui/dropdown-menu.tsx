function DropdownMenuContent({
  className,
  sideOffset = 4,
  side,
  align,
  alignOffset,
  // SOLVRO PATCH: optional className passthrough for the Positioner — same
  // patch as ui/popover.tsx. Base-UI's Positioner carries an inline
  // `transform`, which creates its own stacking context, so the Popup's
  // `z-50` below never competes with page-level z-indexes (e.g. the Gantt's
  // sticky `z-30` header painted over the toolbar's Color-by menu). Callers
  // that open over such content set the z-index on the Positioner via this
  // prop; default unset keeps every existing menu unchanged.
  positionerClassName,
  ...props
}: Omit<React.ComponentProps<typeof DropdownMenuPrimitive.Popup>, "className"> &
  Pick<
    React.ComponentProps<typeof DropdownMenuPrimitive.Positioner>,
    "sideOffset" | "side" | "align" | "alignOffset"
  > & { className?: string; positionerClassName?: string }) {
  return (
    <DropdownMenuPrimitive.Portal>
      <DropdownMenuPrimitive.Positioner
        sideOffset={sideOffset}
        side={side}
        align={align}
        alignOffset={alignOffset}
        // SOLVRO PATCH: see positionerClassName comment above.
        className={cn(positionerClassName)}
      >
        <DropdownMenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            // SOLVRO PATCH — upstream's bare `border` has no color source in
            // this codebase (no global border-color reset), so popups drew a
            // text-colored outline: near-white in dark, near-black in light.
            // `border-border` routes to the outline-variant hairline.
            "z-50 max-h-(--available-height) min-w-[8rem] origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-md border border-border bg-popover p-1 text-popover-foreground shadow-md data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-ending-style:animate-out data-ending-style:fade-out-0 data-ending-style:zoom-out-95 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95",
            className
          )}
          {...props}
        />
      </DropdownMenuPrimitive.Positioner>
    </DropdownMenuPrimitive.Portal>
  )
}

